// if else
// Definir um fluxo para somar ou multiplicar dois números usando if/else

const numero1 = 10;
const numero2 = 5;
const operacao = 'soma';

if (operacao === 'soma') {
    console.log('O resultado da soma é:', numero1 + numero2);

} else {
    console.log('O resultado da multiplicação é:', numero1 * numero2);
}
